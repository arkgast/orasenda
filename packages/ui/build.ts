// Generates components.css from design/system/components/bundle.css without its font @import.
// Run: node build.ts [--out <out>].
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "design", "system", "components", "bundle.css");

export function generate(css: string): string {
  const out = css.replace(/^@import\s[^;]*;[ \t]*\r?\n/gm, "");
  if (/@import|url\(/.test(out)) throw new Error("bundle.css still has an @import or url()");
  return `/* Generated by build.ts from design/system/components/bundle.css. Do not edit. */\n${out}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf("--out");
  const out = i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : join(here, "components.css");
  try {
    writeFileSync(out, generate(readFileSync(source, "utf8")));
  } catch (e) {
    console.error(`ui build failed: ${(e as Error).message}`);
    process.exit(1);
  }
}
