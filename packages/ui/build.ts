// Generates, from design/system/components/:
// - components.css: bundle.css without its font @import.
// - components.d.ts: index.d.ts, copied here so its `import ... from 'react'` resolves against
//   packages/ui/node_modules (design/system has no node_modules, so React types were lost, #35).
// Run: node build.ts [--out <css>] [--out-types <d.ts>].
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const components = join(here, "..", "..", "design", "system", "components");

export function generate(css: string): string {
  const out = css.replace(/^@import\s[^;]*;[ \t]*\r?\n/gm, "");
  if (/@import|url\(/.test(out)) throw new Error("bundle.css still has an @import or url()");
  return `/* Generated by build.ts from design/system/components/bundle.css. Do not edit. */\n${out}`;
}

export function generateTypes(dts: string): string {
  // A relative import would point back into design/system and break once the file moves here.
  // Covers `from './x'`, `import './x'`, `import('./x')` and `/// <reference path="./x" />`.
  if (/\bfrom\s+['"]\.|\bimport\s*\(?\s*['"]\.|<reference\s+path\s*=/.test(dts)) {
    throw new Error("index.d.ts has a relative import");
  }
  return `// Generated by build.ts from design/system/components/index.d.ts. Do not edit.\n${dts}`;
}

export function arg(argv: readonly string[], name: string, fallback: string): string {
  const i = argv.indexOf(name);
  if (i < 0) return fallback;
  const value = argv[i + 1];
  if (!value || value.startsWith("--")) throw new Error(`${name} needs a value`);
  return value;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    writeFileSync(
      arg(process.argv, "--out", join(here, "components.css")),
      generate(readFileSync(join(components, "bundle.css"), "utf8")),
    );
    writeFileSync(
      arg(process.argv, "--out-types", join(here, "components.d.ts")),
      generateTypes(readFileSync(join(components, "index.d.ts"), "utf8")),
    );
  } catch (e) {
    console.error(`ui build failed: ${(e as Error).message}`);
    process.exit(1);
  }
}
